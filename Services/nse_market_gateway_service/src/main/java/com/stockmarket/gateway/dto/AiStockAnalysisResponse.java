package com.stockmarket.gateway.dto;

import com.fasterxml.jackson.annotation.JsonProperty;

import java.io.Serializable;
import java.util.List;

/**
 * ====================================================================================================
 *                 AI ADVISORY DTO: STOCK ANALYSIS RESPONSE RECORD
 * ====================================================================================================
 *
 * Architectural Purpose:
 * Immutable Data Transfer Object encapsulating the synthesized output produced by the dual-engine
 * AI advisory system (Spring AI and LangChain4j). Combines quantitative TRM execution levels,
 * binary event risks, actionable recommendations, and the complete LLM reasoning output.
 *
 * Annotations Applied:
 * <ul>
 *   <li><b>@JsonProperty</b>: Guarantees standardized JSON serialization across all microservice layers.</li>
 * </ul>
 *
 * Real-Time Trading Scenario:
 * Consumed by autonomous execution algos and frontend trading dashboards. Provides discrete numeric
 * values (invalidationStopLoss, target1, target2, trmSetupScore) that can be immediately routed
 * to broker order management systems (OMS) without parsing unstructured text.
 *
 * @param symbol               Analyzed NSE ticker symbol.
 * @param generatedAt          ISO-8601 UTC timestamp of advisory generation.
 * @param recommendation       Categorical rating (e.g., "STRONG_BUY", "ACCUMULATE_TRM", "HOLD", "AVOID").
 * @param trmSetupScore        Objective quantitative setup score from 0 to 100.
 * @param binaryEventRisk      Assessment of imminent binary risk events (e.g., "LOW", "MODERATE", "HIGH - Earnings Approaching").
 * @param executiveSummary     Concise paragraph summarizing the core fundamental and technical thesis.
 * @param keyCatalysts         Bullet points highlighting forward growth drivers and technical triggers.
 * @param invalidationStopLoss Structural price floor where the thesis is invalidated.
 * @param target1              Conservative first profit-taking price level.
 * @param target2              Base case secondary profit-taking price level.
 * @param fullAnalysisMarkdown Complete formatted Markdown dossier generated by the LLM.
 * @param modelUsed            Identifier of the AI model that produced the analysis (e.g., "deepseek-r1:1.5b").
 * @param routingReason        Diagnostic rationale detailing why that specific model was routed.
 */
public record AiStockAnalysisResponse(
        @JsonProperty("symbol") String symbol,
        @JsonProperty("generatedAt") String generatedAt,
        @JsonProperty("recommendation") String recommendation,
        @JsonProperty("trmSetupScore") int trmSetupScore,
        @JsonProperty("binaryEventRisk") String binaryEventRisk,
        @JsonProperty("executiveSummary") String executiveSummary,
        @JsonProperty("keyCatalysts") List<String> keyCatalysts,
        @JsonProperty("invalidationStopLoss") double invalidationStopLoss,
        @JsonProperty("target1") double target1,
        @JsonProperty("target2") double target2,
        @JsonProperty("fullAnalysisMarkdown") String fullAnalysisMarkdown,
        @JsonProperty("modelUsed") String modelUsed,
        @JsonProperty("routingReason") String routingReason
) implements Serializable {}
